import json
import pathlib
import urllib.request
from typing import Any

ROOT = pathlib.Path(__file__).resolve().parent.parent

PY_OUT = ROOT / "python/mirage/utils/generated/google_vocabulary.py"
TS_OUT = (
    ROOT / "typescript/packages/core/src/utils/generated/google_vocabulary.ts"
)

LICENSE_PY = (ROOT / "scripts/gen_specs.py").read_text().split("\n")[:13]

# Each app mount renders its API's response, whose property names and enum
# values are in every file whatever its text says: the schemas the response
# reaches from its root, which leaves out the request types.
APIS = (
    ("DOCS", "docs", "v1", "Document"),
    ("SHEETS", "sheets", "v4", "Spreadsheet"),
    ("SLIDES", "slides", "v1", "Presentation"),
)

NOTE = (
    "GENERATED by scripts/gen_google_vocabulary.py from the Docs, Sheets and\n"
    "Slides discovery documents: every property name and enum value of the\n"
    "schemas a get response reaches, lowercased. Do not edit by hand; run the\n"
    "script and commit both trees' output together."
)

WIDTH = 79


def discovery(api: str, version: str) -> Any:
    url = f"https://{api}.googleapis.com/$discovery/rest?version={version}"
    with urllib.request.urlopen(url) as response:
        data: bytes = response.read()
    return json.loads(data)


def words_of(
    node: Any, schemas: dict[str, Any], found: set[str], seen: set[str]
) -> None:
    if isinstance(node, dict):
        ref = node.get("$ref")
        if isinstance(ref, str) and ref not in seen:
            seen.add(ref)
            words_of(schemas[ref], schemas, found, seen)
        properties = node.get("properties")
        if isinstance(properties, dict):
            found.update(name.lower() for name in properties)
        for value in node.get("enum", ()):
            found.add(str(value).lower())
        for value in node.values():
            words_of(value, schemas, found, seen)
    elif isinstance(node, list):
        for value in node:
            words_of(value, schemas, found, seen)


def rows(words: list[str], indent: str, quote: str) -> str:
    lines: list[str] = []
    line = ""
    for word in words:
        item = f"{quote}{word}{quote},"
        if line and len(indent) + len(line) + 1 + len(item) > WIDTH:
            lines.append(indent + line)
            line = ""
        line = f"{line} {item}" if line else item
    lines.append(indent + line)
    return "\n".join(lines)


def main() -> None:
    sets: dict[str, list[str]] = {}
    for name, api, version, root in APIS:
        schemas = discovery(api, version)["schemas"]
        found: set[str] = set()
        words_of({"$ref": root}, schemas, found, set())
        sets[name] = sorted(found)
    py_head = "\n".join(LICENSE_PY)
    py_note = "\n".join(f"# {line}" for line in NOTE.split("\n"))
    py_sets = "\n\n".join(
        f"{name}_WORDS: frozenset[str] = frozenset(\n    {{\n"
        f"{rows(words, '        ', chr(34))}\n    }}\n)"
        for name, words in sets.items()
    )
    PY_OUT.write_text(f"{py_head}\n\n{py_note}\n\n{py_sets}\n")
    ts_head = "\n".join(line.replace("#", "//", 1) for line in LICENSE_PY)
    ts_note = "\n".join(f"// {line}" for line in NOTE.split("\n"))
    ts_sets = "\n\n".join(
        f"export const {name}_WORDS: ReadonlySet<string> = new Set([\n"
        f"{rows(words, '  ', chr(39))}\n])"
        for name, words in sets.items()
    )
    TS_OUT.write_text(f"{ts_head}\n\n{ts_note}\n\n{ts_sets}\n")


if __name__ == "__main__":
    main()
